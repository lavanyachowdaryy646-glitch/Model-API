def health():
    return jsonify({
        "status": "Healthy",
        "model": "Loaded successfully"
    })


@app.route("/predict", methods=["POST"])
def predict():

    data = request.get_json(silent=True)

    if not isinstance(data, dict):
        return jsonify({"error": "Send valid JSON data"}), 400

    fields = [
        "tenure",
        "monthly_charges",
        "support_calls",
        "contract_months"
    ]

    missing = [field for field in fields if field not in data]

    if missing:
        return jsonify({
            "error": "Missing required fields",
            "missing_fields": missing
        }), 400

    try:
        values = [float(data[field]) for field in fields]
    except (ValueError, TypeError):
        return jsonify({"error": "All values must be numbers"}), 400

    if not np.all(np.isfinite(values)):
        return jsonify({"error": "Values must be finite"}), 400

    tenure_value, charge_value, calls_value, contract_value = values

    if not tenure_value.is_integer() or not 1 <= tenure_value <= 72:
        return jsonify({"error": "Tenure must be 1 to 72"}), 400

    if not 20 <= charge_value <= 150:
        return jsonify({"error": "Monthly charges must be 20 to 150"}), 400

    if not calls_value.is_integer() or not 0 <= calls_value <= 10:
        return jsonify({"error": "Support calls must be 0 to 10"}), 400

    if contract_value not in [1, 12, 24]:
        return jsonify({"error": "Contract must be 1, 12 or 24"}), 400

    customer = np.array(values).reshape(1, -1)

    result = int(model.predict(customer)[0])

    probability = float(model.predict_proba(customer)[0][1])

    return jsonify({
        "project": "Customer Churn Prediction",
        "prediction": result,
        "result": "Customer Will Churn" if result == 1 else "Customer Will Stay",
        "churn_probability": round(probability * 100, 2),
        "status": "Success"
    })


